def load_json(path: Path) -> dict:
    if not path.exists():
        raise SystemExit(f"missing input artifact: {path}")
    return json.loads(path.read_text(encoding="utf-8"))


def tool_status(sim_status: dict, tool_name: str) -> dict:
    tools = sim_status.get("tools") if isinstance(sim_status.get("tools"), list) else []
    return next((tool for tool in tools if isinstance(tool, dict) and tool.get("tool") == tool_name), {})


